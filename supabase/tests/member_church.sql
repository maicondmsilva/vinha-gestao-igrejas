begin;
create extension if not exists pgtap with schema extensions;
select no_plan();
create function pg_temp.mc(t text) returns uuid language sql immutable as $$select md5('member-church-test-'||t)::uuid$$;
create function pg_temp.actor(t text) returns text language sql as $$select set_config('request.jwt.claims',jsonb_build_object('sub',pg_temp.mc(t),'role','authenticated')::text,true)$$;
insert into auth.users(id,instance_id,aud,role,email,email_confirmed_at,created_at,updated_at) select pg_temp.mc(t),'00000000-0000-0000-0000-000000000000','authenticated','authenticated',t||'-church@example.invalid',now(),now(),now() from unnest(array['owner','member','foreign']) t;
insert into public.organizations(id,name,slug,status) values(pg_temp.mc('org'),'Igrejas fictícias','member-church-test','active'),(pg_temp.mc('other'),'Outro ministério fictício','member-church-other','active');
insert into public.organization_units(id,organization_id,name,slug,unit_type) values(pg_temp.mc('a'),pg_temp.mc('org'),'Igreja A','a','headquarters'),(pg_temp.mc('b'),pg_temp.mc('org'),'Igreja B','b','campus'),(pg_temp.mc('c'),pg_temp.mc('other'),'Igreja externa','c','headquarters');
insert into public.organization_memberships(id,organization_id,user_id,default_unit_id,role,status) values(pg_temp.mc('owner-m'),pg_temp.mc('org'),pg_temp.mc('owner'),pg_temp.mc('a'),'owner','active'),(pg_temp.mc('member-m'),pg_temp.mc('org'),pg_temp.mc('member'),pg_temp.mc('a'),'member','active');
insert into public.people(id,organization_id,unit_id,auth_user_id,full_name,status) values(pg_temp.mc('person'),pg_temp.mc('org'),pg_temp.mc('a'),pg_temp.mc('member'),'Membro fictício','active');
create function pg_temp.pending() returns uuid language sql security definer as $$select id from private.member_church_transfers where user_id=pg_temp.mc('member') and status='pending'$$;
create function pg_temp.review(d text) returns jsonb language sql as $$select public.member_church_admin(pg_temp.mc('org'),'review',pg_temp.pending(),null,jsonb_build_object('decision',d,'reason','Conferência fictícia de transferência'))$$;
select ok(not has_table_privilege('authenticated','private.member_church_preferences','select'),'preferência sem acesso direto');
select ok(not has_table_privilege('authenticated','private.member_church_transfers','update'),'transferência sem escrita direta');
select ok(not has_function_privilege('anon','public.member_church(uuid,text,uuid,uuid)','execute'),'visitante não solicita transferência');
select pg_temp.actor('owner');
set local role authenticated;
select lives_ok($$select public.member_church_admin(pg_temp.mc('org'),'publish',null,pg_temp.mc('a'),'{"kind":"notice","title":"Aviso igreja A","body":"Público A","url":""}')$$,'publicação A autorizada');
select lives_ok($$select public.member_church_admin(pg_temp.mc('org'),'publish',null,pg_temp.mc('b'),'{"kind":"video","title":"Vídeo igreja B","body":"Público B","url":"https://example.com/video"}')$$,'publicação B autorizada');
select throws_ok($$select public.member_church_admin(pg_temp.mc('org'),'publish',null,pg_temp.mc('c'),'{"kind":"notice","title":"Não publicar","body":"","url":""}')$$,'42501','member_unit_denied','não publica em outro ministério');
select pg_temp.actor('member');
select lives_ok($$select public.member_church(pg_temp.mc('org'),'select',pg_temp.mc('b'))$$,'membro seleciona conteúdo B imediatamente');
select is(public.member_church(pg_temp.mc('org'),'state')->>'selectedUnit',pg_temp.mc('b')::text,'preferência persistida');
select is(public.member_church(pg_temp.mc('org'),'state')->>'officialUnit',pg_temp.mc('a')::text,'vínculo permanece na origem');
select throws_ok($$select public.member_church(pg_temp.mc('org'),'select',pg_temp.mc('c'))$$,'42501','member_unit_denied','seleção de outro ministério recusada');
select throws_ok($$select public.member_church_admin(pg_temp.mc('org'),'list')$$,'42501','member_review_denied','membro não vê fila de terceiros');
select lives_ok($$select public.member_church(pg_temp.mc('org'),'request',pg_temp.mc('b'))$$,'pedido separado da preferência');
select lives_ok($$select public.member_church(pg_temp.mc('org'),'request',pg_temp.mc('b'))$$,'repetição não duplica');
reset role;
select is((select count(*)::integer from private.member_church_transfers where user_id=pg_temp.mc('member')),1,'uma solicitação');
select is((select unit_id from public.people where id=pg_temp.mc('person')),pg_temp.mc('a'),'pedido não transfere pessoa');
select is((select role::text from public.organization_memberships where id=pg_temp.mc('member-m')),'member','pedido não altera papel');
select pg_temp.actor('foreign');
set local role authenticated;
select is(jsonb_array_length(public.member_church(pg_temp.mc('org'),'state')->'transfers'),0,'outra conta não recebe histórico alheio');
reset role;
select pg_temp.actor('owner');
set local role authenticated;
select lives_ok($$select public.member_church_admin(pg_temp.mc('org'),'list')$$,'admin consulta fila e publicações');
select lives_ok($$select pg_temp.review('rejected')$$,'recusa registrada');
reset role;
select is((select unit_id from public.people where id=pg_temp.mc('person')),pg_temp.mc('a'),'recusa preserva vínculo');
select pg_temp.actor('member');
set local role authenticated;
select lives_ok($$select public.member_church(pg_temp.mc('org'),'request',pg_temp.mc('b'))$$,'novo pedido após recusa');
reset role;
select pg_temp.actor('owner');
set local role authenticated;
select lives_ok($$select pg_temp.review('approved')$$,'aprovação aplica transferência');
reset role;
select is((select unit_id from public.people where id=pg_temp.mc('person')),pg_temp.mc('b'),'pessoa vinculada ao destino');
select is((select default_unit_id from public.organization_memberships where id=pg_temp.mc('member-m')),pg_temp.mc('b'),'preferência oficial sincronizada');
select is((select role::text from public.organization_memberships where id=pg_temp.mc('member-m')),'member','aprovação não promove acesso');
select is((select count(*)::integer from public.membership_unit_access where membership_id=pg_temp.mc('member-m')),0,'aprovação não concede escopos');
select is((select count(*)::integer from public.people where auth_user_id=pg_temp.mc('member')),1,'mesmo cadastro sem duplicação');
set local role anon;
select is(jsonb_array_length(public.member_public_feed(pg_temp.mc('org'),pg_temp.mc('b'))->'items'),1,'feed público B contém apenas B');
select is(public.member_public_feed(pg_temp.mc('org'),pg_temp.mc('b'))->'items'->0->>'title','Vídeo igreja B','conteúdo correto sem aprovação necessária');
select throws_ok($$select public.member_public_feed(pg_temp.mc('org'),pg_temp.mc('c'))$$,'42501','member_unit_denied','feed recusa unidade externa');
reset role;
select ok(exists(select 1 from public.audit_logs where organization_id=pg_temp.mc('org') and action='member.church.review'),'decisão auditada');
select pg_temp.actor('member');
set local role authenticated;
select lives_ok($$select public.member_church(pg_temp.mc('org'),'request',pg_temp.mc('a'))$$,'pode solicitar retorno');
select throws_ok($$select pg_temp.review('approved')$$,'42501','member_review_denied','membro não aprova próprio pedido');
select lives_ok($$select public.member_church(pg_temp.mc('org'),'cancel',null,pg_temp.pending())$$,'cancela apenas próprio pedido');
reset role;
select is((select unit_id from public.people where id=pg_temp.mc('person')),pg_temp.mc('b'),'cancelamento preserva vínculo');
select pg_temp.actor('member');
set local role authenticated;
select lives_ok($$select public.member_church(pg_temp.mc('org'),'request',pg_temp.mc('a'))$$,'novo pedido depois do cancelamento');
reset role;
select pg_temp.actor('owner');
update public.organization_memberships set role='leader' where id=pg_temp.mc('member-m');
set local role authenticated;
select throws_ok($$select pg_temp.review('approved')$$,'40001','member_transfer_access_review','cargos exigem revisão separada');
reset role;
update public.organization_memberships set role='member',status='suspended' where id=pg_temp.mc('member-m');
set local role authenticated;
select throws_ok($$select pg_temp.review('approved')$$,'40001','member_transfer_identity','suspensão impede aprovação');
reset role;
update public.organization_memberships set status='active' where id=pg_temp.mc('member-m');
update public.people set unit_id=pg_temp.mc('a') where id=pg_temp.mc('person');
set local role authenticated;
select throws_ok($$select pg_temp.review('approved')$$,'40001','member_transfer_identity','vínculo alterado exige nova conferência');
reset role;
insert into private.member_publications(organization_id,unit_id,kind,title,body) values(pg_temp.mc('org'),pg_temp.mc('b'),'notice','Rascunho privado','Não deve aparecer');
set local role anon;
select is(jsonb_array_length(public.member_public_feed(pg_temp.mc('org'),pg_temp.mc('b'))->'items'),1,'rascunho não aparece no feed');
reset role;
select pg_temp.actor('owner');
create function pg_temp.post_id() returns uuid language sql security definer as $$select id from private.member_publications where organization_id=pg_temp.mc('org') and title='Vídeo igreja B'$$;
set local role authenticated;
select lives_ok($$select public.member_church_admin(pg_temp.mc('org'),'unpublish',pg_temp.post_id())$$,'admin retira publicação');
set local role anon;
select is(jsonb_array_length(public.member_public_feed(pg_temp.mc('org'),pg_temp.mc('b'))->'items'),0,'publicação retirada desaparece do feed público');
reset role;
select * from finish();
rollback;
